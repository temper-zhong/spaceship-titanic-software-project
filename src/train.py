import json
import platform
import sys
import time
from pathlib import Path
from typing import Any

import catboost
import numpy as np
import pandas as pd
import sklearn
import xgboost
from sklearn.dummy import DummyClassifier
from sklearn.metrics import (
    accuracy_score,
    brier_score_loss,
    f1_score,
    log_loss,
    precision_score,
    recall_score,
    roc_auc_score,
)

from src.pipeline import (
    MODEL_NAMES,
    build_grouped_splits,
    build_model,
    engineer_features,
    extract_feature_importance,
    fold_assignment,
    load_official_data,
    passenger_groups,
)


def evaluate_probabilities(
    target: np.ndarray, probabilities: np.ndarray, threshold: float
) -> dict[str, float]:
    predictions = probabilities >= threshold
    return {
        "accuracy": float(accuracy_score(target, predictions)),
        "roc_auc": float(roc_auc_score(target, probabilities)),
        "precision": float(precision_score(target, predictions, zero_division=0)),
        "recall": float(recall_score(target, predictions, zero_division=0)),
        "f1": float(f1_score(target, predictions, zero_division=0)),
        "log_loss": float(log_loss(target, probabilities, labels=[False, True])),
        "brier_score": float(brier_score_loss(target, probabilities)),
    }


def find_best_blend(
    oof_probabilities: dict[str, np.ndarray], target: np.ndarray
) -> tuple[dict[str, float], float, float]:
    names = list(oof_probabilities)
    units = 10
    best_accuracy = -1.0
    best_threshold = 0.5
    best_weights = {name: 1.0 / len(names) for name in names}

    allocations = (
        values
        for values in itertools.product(range(units + 1), repeat=len(names))
        if sum(values) == units
    )
    for allocation in allocations:
        weights = np.asarray(allocation, dtype=float) / units
        blended = sum(
            weight * oof_probabilities[name]
            for name, weight in zip(names, weights, strict=True)
        )
        for threshold in np.arange(0.44, 0.561, 0.002):
            accuracy = accuracy_score(target, blended >= threshold)
            if accuracy > best_accuracy + 1e-12:
                best_accuracy = float(accuracy)
                best_threshold = float(threshold)
                best_weights = {
                    name: float(weight)
                    for name, weight in zip(names, weights, strict=True)
                }
    return best_weights, best_threshold, best_accuracy


def load_parameter_overrides(path: Path | None) -> dict[str, dict[str, Any]]:
    if path is None or not path.exists():
        return {}
    payload = json.loads(path.read_text(encoding="utf-8"))
    params = payload.get("best_parameters", payload)
    if not isinstance(params, dict):
        raise ValueError("Parameter file must contain a best_parameters object.")
    return {str(name): dict(values) for name, values in params.items()}


def write_model_summary(metrics: dict[str, Any], path: Path) -> None:
    rows = []
    for name, result in metrics["models"].items():
        fold_text = ", ".join(f"{score:.4f}" for score in result["fold_accuracy"])
        rows.append(
            f"| {name} | {result['accuracy']:.4f} | {result['roc_auc']:.4f} | "
            f"{result['f1']:.4f} | {fold_text} |"
        )
    ensemble = metrics["ensemble"]
    rows.append(
        f"| blended_ensemble | {ensemble['accuracy']:.4f} | {ensemble['roc_auc']:.4f} | "
        f"{ensemble['f1']:.4f} | {', '.join(f'{x:.4f}' for x in ensemble['fold_accuracy'])} |"
    )
    weights = ", ".join(
        f"{name}={weight:.1f}" for name, weight in ensemble["weights"].items()
    )
    content = f"""# Model Results

Generated by `python -m src.train` using grouped out-of-fold predictions.

| Model | OOF accuracy | OOF ROC-AUC | OOF F1 | Fold accuracy |
|---|---:|---:|---:|---|
{chr(10).join(rows)}

- Validation: {metrics['validation']['method']}, {metrics['validation']['folds']} folds
- Blend: {weights}
- Classification threshold: {ensemble['threshold']:.3f}
- Test predictions marked `True`: {metrics['submission']['true_rate']:.2%}
"""
    path.write_text(content, encoding="utf-8")


def run_training(args: argparse.Namespace) -> dict[str, Any]:
    data_dir = args.data_dir.resolve()
    output_dir = args.output_dir.resolve()
    train, test, sample = load_official_data(data_dir)

    target = train["Transported"].astype(bool).to_numpy()
    groups = passenger_groups(train["PassengerId"])
    train_features, test_features = engineer_features(
        train.drop(columns="Transported"), test
    )

    fold_count = 3 if args.quick else args.folds
    splits = build_grouped_splits(
        train_features, target, groups, folds=fold_count, seed=args.seed
    )
    parameter_overrides = load_parameter_overrides(args.params_file)

    output_dir.mkdir(parents=True, exist_ok=True)
    fold_assignment(train["PassengerId"], splits).to_csv(
        output_dir / "fold_assignments.csv", index=False
    )

    oof_probabilities: dict[str, np.ndarray] = {}
    test_probabilities: dict[str, np.ndarray] = {}
    model_metrics: dict[str, dict[str, Any]] = {}
    fold_rows: list[dict[str, Any]] = []
    importance_frames: list[pd.DataFrame] = []

    dummy_start = time.perf_counter()
    dummy_oof = np.zeros(len(train_features), dtype=float)
    dummy_fold_accuracy: list[float] = []
    print("\nTraining dummy_classifier...")
    for fold_number, (fit_index, validation_index) in enumerate(splits, start=1):
        dummy = DummyClassifier(strategy="prior")
        dummy.fit(train_features.iloc[fit_index], target[fit_index])
        validation_probability = dummy.predict_proba(
            train_features.iloc[validation_index]
        )[:, 1]
        dummy_oof[validation_index] = validation_probability
        accuracy = float(
            accuracy_score(target[validation_index], validation_probability >= 0.5)
        )
        dummy_fold_accuracy.append(accuracy)
        fold_rows.append(
            {
                "Model": "dummy_classifier",
                "Fold": fold_number,
                "ValidationRows": int(len(validation_index)),
                "Accuracy": accuracy,
                "ROC_AUC": 0.5,
            }
        )
    dummy_metrics = evaluate_probabilities(target, dummy_oof, threshold=0.5)
    # A pooled AUC across folds is not meaningful when each fold has a slightly
    # different fitted class prior. Every within-fold Dummy AUC is exactly 0.5.
    dummy_metrics["roc_auc"] = 0.5
    dummy_metrics.update(
        {
            "fold_accuracy": dummy_fold_accuracy,
            "fold_accuracy_mean": float(np.mean(dummy_fold_accuracy)),
            "fold_accuracy_std": float(np.std(dummy_fold_accuracy, ddof=1)),
            "seconds": float(time.perf_counter() - dummy_start),
        }
    )
    model_metrics["dummy_classifier"] = dummy_metrics
    print(f"  OOF accuracy={dummy_metrics['accuracy']:.4f}, ROC-AUC=0.5000")

    for model_name in MODEL_NAMES:
        start = time.perf_counter()
        oof = np.zeros(len(train_features), dtype=float)
        test_fold_probabilities: list[np.ndarray] = []
        fold_accuracy: list[float] = []
        model_importances: list[pd.DataFrame] = []

        print(f"\nTraining {model_name}...")
        for fold_number, (fit_index, validation_index) in enumerate(splits, start=1):
            estimator = build_model(
                model_name,
                seed=args.seed + fold_number,
                quick=args.quick,
                overrides=parameter_overrides.get(model_name),
            )
            estimator.fit(train_features.iloc[fit_index], target[fit_index])
            validation_probability = estimator.predict_proba(
                train_features.iloc[validation_index]
            )[:, 1]
            test_probability = estimator.predict_proba(test_features)[:, 1]
            oof[validation_index] = validation_probability
            test_fold_probabilities.append(test_probability)
            accuracy = float(
                accuracy_score(target[validation_index], validation_probability >= 0.5)
            )
            fold_accuracy.append(accuracy)
            fold_rows.append(
                {
                    "Model": model_name,
                    "Fold": fold_number,
                    "ValidationRows": int(len(validation_index)),
                    "Accuracy": accuracy,
                    "ROC_AUC": float(
                        roc_auc_score(target[validation_index], validation_probability)
                    ),
                }
            )
            importance = extract_feature_importance(estimator, model_name)
            importance["Fold"] = fold_number
            model_importances.append(importance)
            print(f"  fold {fold_number}/{fold_count}: accuracy={accuracy:.4f}")

        elapsed = time.perf_counter() - start
        metrics = evaluate_probabilities(target, oof, threshold=0.5)
        metrics["fold_accuracy"] = fold_accuracy
        metrics["fold_accuracy_mean"] = float(np.mean(fold_accuracy))
        metrics["fold_accuracy_std"] = float(np.std(fold_accuracy, ddof=1))
        metrics["seconds"] = float(elapsed)
        model_metrics[model_name] = metrics
        oof_probabilities[model_name] = oof
        test_probabilities[model_name] = np.mean(test_fold_probabilities, axis=0)

        combined_importance = pd.concat(model_importances, ignore_index=True)
        mean_importance = (
            combined_importance.groupby(["Model", "Feature"], as_index=False)["Importance"]
            .mean()
            .sort_values("Importance", ascending=False)
        )
        mean_importance["Rank"] = (
            mean_importance.groupby("Model")["Importance"]
            .rank(method="first", ascending=False)
            .astype(int)
        )
        importance_frames.append(mean_importance)
        print(
            f"  OOF accuracy={metrics['accuracy']:.4f}, "
            f"ROC-AUC={metrics['roc_auc']:.4f}, time={elapsed:.1f}s"
        )

    weights, threshold, _ = find_best_blend(oof_probabilities, target)
    blended_oof = sum(weights[name] * oof_probabilities[name] for name in MODEL_NAMES)
    blended_test = sum(weights[name] * test_probabilities[name] for name in MODEL_NAMES)
    ensemble_metrics = evaluate_probabilities(target, blended_oof, threshold=threshold)
    ensemble_fold_accuracy = []
    for fold_number, (_, validation_index) in enumerate(splits, start=1):
        accuracy = float(
            accuracy_score(
                target[validation_index], blended_oof[validation_index] >= threshold
            )
        )
        ensemble_fold_accuracy.append(accuracy)
        fold_rows.append(
            {
                "Model": "blended_ensemble",
                "Fold": fold_number,
                "ValidationRows": int(len(validation_index)),
                "Accuracy": accuracy,
                "ROC_AUC": float(
                    roc_auc_score(target[validation_index], blended_oof[validation_index])
                ),
            }
        )
    ensemble_metrics.update(
        {
            "weights": weights,
            "threshold": threshold,
            "fold_accuracy": ensemble_fold_accuracy,
            "fold_accuracy_mean": float(np.mean(ensemble_fold_accuracy)),
            "fold_accuracy_std": float(np.std(ensemble_fold_accuracy, ddof=1)),
        }
    )

    predictions = blended_test >= threshold
    submission = pd.DataFrame(
        {"PassengerId": test["PassengerId"], "Transported": predictions.astype(bool)}
    )
    if submission.shape != sample.shape:
        raise AssertionError("Submission shape does not match sample_submission.csv.")
    if not submission["PassengerId"].equals(sample["PassengerId"]):
        raise AssertionError("Submission passenger order changed.")
    if submission["PassengerId"].duplicated().any():
        raise AssertionError("Submission contains duplicate passenger IDs.")
    if submission["Transported"].dtype != bool:
        raise AssertionError("Submission predictions must be Boolean.")

    oof_output = pd.DataFrame(
        {
            "PassengerId": train["PassengerId"],
            "Transported": target,
            "dummy_classifier_probability": dummy_oof,
            **{
                f"{name}_probability": oof_probabilities[name]
                for name in MODEL_NAMES
            },
            "ensemble_probability": blended_oof,
            "ensemble_prediction": blended_oof >= threshold,
        }
    )
    oof_output["correct"] = oof_output["Transported"].eq(
        oof_output["ensemble_prediction"]
    )
    oof_output["error_type"] = np.select(
        [
            oof_output["Transported"] & ~oof_output["ensemble_prediction"],
            ~oof_output["Transported"] & oof_output["ensemble_prediction"],
        ],
        ["false_negative", "false_positive"],
        default="correct",
    )

    comparison_rows = []
    for name, values in model_metrics.items():
        comparison_rows.append(
            {
                "Model": name,
                "Threshold": 0.5,
                "Accuracy": values["accuracy"],
                "ROC_AUC": values["roc_auc"],
                "Precision": values["precision"],
                "Recall": values["recall"],
                "F1": values["f1"],
                "LogLoss": values["log_loss"],
                "BrierScore": values["brier_score"],
                "FoldAccuracyStd": values["fold_accuracy_std"],
                "Seconds": values["seconds"],
            }
        )
    comparison_rows.append(
        {
            "Model": "blended_ensemble",
            "Threshold": threshold,
            "Accuracy": ensemble_metrics["accuracy"],
            "ROC_AUC": ensemble_metrics["roc_auc"],
            "Precision": ensemble_metrics["precision"],
            "Recall": ensemble_metrics["recall"],
            "F1": ensemble_metrics["f1"],
            "LogLoss": ensemble_metrics["log_loss"],
            "BrierScore": ensemble_metrics["brier_score"],
            "FoldAccuracyStd": ensemble_metrics["fold_accuracy_std"],
            "Seconds": sum(x["seconds"] for x in model_metrics.values()),
        }
    )

    submission.to_csv(output_dir / "submission.csv", index=False)
    oof_output.to_csv(output_dir / "oof_predictions.csv", index=False)
    pd.DataFrame(comparison_rows).sort_values("Accuracy", ascending=False).to_csv(
        output_dir / "model_comparison.csv", index=False
    )
    pd.DataFrame(fold_rows).to_csv(output_dir / "fold_scores.csv", index=False)
    pd.concat(importance_frames, ignore_index=True).to_csv(
        output_dir / "feature_importance.csv", index=False
    )

    metrics: dict[str, Any] = {
        "environment": {
            "python": platform.python_version(),
            "pandas": pd.__version__,
            "numpy": np.__version__,
            "scikit_learn": sklearn.__version__,
            "xgboost": xgboost.__version__,
            "catboost": catboost.__version__,
        },
        "data": {
            "train_rows": int(len(train)),
            "test_rows": int(len(test)),
            "engineered_features": int(train_features.shape[1]),
            "target_true_rate": float(target.mean()),
        },
        "validation": {
            "method": "StratifiedGroupKFold grouped by PassengerId prefix",
            "folds": fold_count,
            "seed": args.seed,
        },
        "parameter_file": str(args.params_file) if args.params_file else None,
        "models": model_metrics,
        "ensemble": ensemble_metrics,
        "submission": {
            "path": str(output_dir / "submission.csv"),
            "rows": int(len(submission)),
            "true_rate": float(predictions.mean()),
        },
    }
    (output_dir / "metrics.json").write_text(
        json.dumps(metrics, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    write_model_summary(metrics, output_dir / "model_summary.md")

    print("\nFinished.")
    print(f"Ensemble OOF accuracy: {ensemble_metrics['accuracy']:.4f}")
    print(f"Submission: {output_dir / 'submission.csv'}")
    return metrics


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=Path("raw data"))
    parser.add_argument("--output-dir", type=Path, default=Path("outputs"))
    parser.add_argument("--folds", type=int, default=5)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--params-file", type=Path, default=Path("outputs/best_params.json")
    )
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args(argv)
    if args.folds < 3:
        parser.error("--folds must be at least 3")
    if args.params_file and not args.params_file.exists():
        args.params_file = None
    return args


def main(argv: list[str] | None = None) -> int:
    try:
        run_training(parse_args(argv))
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
